/**
 * IMAP/SMTP accounts, configured in the web app: the account list lives in
 * /config/accounts.json, passwords in /config/passwords/ (mode 600), and from those
 * the server writes mbsyncrc and msmtprc itself — nobody edits them by hand.
 * Mail goes to /mail/imap/<id>/ (one Maildir folder per IMAP folder).
 */

const MBSYNC = process.env.MBSYNC_BIN ?? 'mbsync'
const MSMTP = process.env.MSMTP_BIN ?? 'msmtp'
const CONFIG_DIR = process.env.CONFIG_DIR ?? '/config'
const MAIL_ROOT = process.env.MAIL_ROOT ?? '/mail'
const ACCOUNTS_FILE = path.join(CONFIG_DIR, 'accounts.json')
const PASS_DIR = path.join(CONFIG_DIR, 'passwords')
const MBSYNC_CONFIG = path.join(CONFIG_DIR, 'mbsyncrc')
const MSMTP_CONFIG = path.join(CONFIG_DIR, 'msmtprc')
const IMAP_DIR = path.join(MAIL_ROOT, 'imap')
const CA = '/etc/ssl/certs/ca-certificates.crt'
const TEST_TIMEOUT = 30_000
const SYNC_TIMEOUT = 30 * 60_000

/** tls: TLS from the start (IMAPS 993, SMTPS 465) · starttls: upgrade (143, 587) · none: plain text */
export type Security = 'tls' | 'starttls' | 'none'
export type Server = { host: string; port: number; security: Security; user: string }
export type ImapAccount = {
  id: string; name: string; email: string; imap: Server; smtp: Server; sentFolder: string
  /** set up by proton.ts for a Proton Mail Bridge account; edited only there */
  proton?: { userId: string }
  /** a certificate file to trust instead of the system CAs (Bridge's self-signed one) */
  ca?: string
}
export type AccountInput = Omit<ImapAccount, 'id' | 'sentFolder' | 'proton' | 'ca'> & { id?: string; imapPassword?: string; smtpPassword?: string }

const EMAIL_RE = /^[^\s@"\\]+@[^\s@"\\/]+\.[^\s@"\\/]+$/
const slug = (email: string) => email.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')

// ---- the account list ----------------------------------------------------------------

async function load(): Promise<ImapAccount[]> {
  try { return JSON.parse(await fs.readFile(ACCOUNTS_FILE, 'utf8')).accounts ?? [] } catch { return [] }
}

async function store(accounts: ImapAccount[]) {
  await fs.mkdir(CONFIG_DIR, { recursive: true })
  await fs.writeFile(ACCOUNTS_FILE + '.new', JSON.stringify({ accounts }, null, 2) + '\n', { mode: 0o600 })
  await fs.rename(ACCOUNTS_FILE + '.new', ACCOUNTS_FILE)
  await writeConfigs(accounts, PASS_DIR, IMAP_DIR, CONFIG_DIR)
}

type Status = { syncing: boolean; last?: string; ok?: boolean; error?: string }
const status = new Map<string, Status>()

export async function accounts() {
  return (await load()).map(a => ({ ...a, ...(status.get(a.id) ?? { syncing: false }) }))
}

export async function accountFor(from: string) {
  const addr = (from.match(/<([^>]+)>/)?.[1] ?? from).trim().toLowerCase()
  return (await load()).find(a => a.email.toLowerCase() === addr)
}

// ---- the generated configs -------------------------------------------------------------

const passFile = (dir: string, id: string, kind: 'imap' | 'smtp') => path.join(dir, `${id}.${kind}`)

/** mbsync: quoted strings, backslash escapes */
const q = (s: string) => `"${s.replace(/[\\"]/g, '\\$&')}"`

function mbsyncrc(accounts: ImapAccount[], passDir: string, mailDir: string) {
  return `# generated by drewcmail from accounts.json — edit the accounts in the web app\n\n` + accounts.map(a => {
    const tls = { tls: 'IMAPS', starttls: 'STARTTLS', none: 'None' }[a.imap.security]
    const root = path.join(mailDir, a.id)
    return [
      `IMAPAccount ${a.id}`,
      `Host ${a.imap.host}`,
      `Port ${a.imap.port}`,
      `User ${q(a.imap.user)}`,
      `PassCmd "cat ${passFile(passDir, a.id, 'imap')}"`,  // ids are [a-z0-9-]: no quoting needed
      `TLSType ${tls}`,
      a.imap.security === 'none' ? 'AuthMechs LOGIN' : `CertificateFile ${a.ca ?? CA}`,
      '',
      `IMAPStore ${a.id}-remote`,
      `Account ${a.id}`,
      '',
      `MaildirStore ${a.id}-local`,
      `Path ${q(root + '/')}`,
      `Inbox ${q(path.join(root, 'INBOX'))}`,
      'SubFolders Verbatim',
      '',
      `Channel ${a.id}`,
      `Far :${a.id}-remote:`,
      `Near :${a.id}-local:`,
      // Bridge's All Mail repeats every message (notmuch would merge them, but they would be stored twice)
      a.proton ? 'Patterns * !"All Mail"' : 'Patterns *',
      'Create Both',             // e.g. the Sent folder, when the server has none yet
      'Remove None',
      'Expunge None',
      'SyncState *',
      'CopyArrivalDate yes',
      '',
    ].join('\n')
  }).join('\n')
}

function msmtprc(accounts: ImapAccount[], passDir: string) {
  return `# generated by drewcmail from accounts.json — edit the accounts in the web app\n\n` + accounts.map(a => [
    `account ${a.id}`,
    `host ${a.smtp.host}`,
    `port ${a.smtp.port}`,
    `from ${a.email}`,
    // msmtp only sends a password in the clear when told which method to use
    `auth ${a.smtp.security === 'none' ? 'plain' : 'on'}`,
    `user ${a.smtp.user}`,
    `passwordeval "cat '${passFile(passDir, a.id, 'smtp')}'"`,
    `tls ${a.smtp.security === 'none' ? 'off' : 'on'}`,
    `tls_starttls ${a.smtp.security === 'starttls' ? 'on' : 'off'}`,
    `tls_trust_file ${a.ca ?? CA}`,
    '',
  ].join('\n')).join('\n')
}

async function writeConfigs(accounts: ImapAccount[], passDir: string, mailDir: string, configDir: string) {
  await fs.writeFile(path.join(configDir, 'mbsyncrc'), mbsyncrc(accounts, passDir, mailDir), { mode: 0o600 })
  await fs.writeFile(path.join(configDir, 'msmtprc'), msmtprc(accounts, passDir), { mode: 0o600 })
}

async function writePasswords(dir: string, id: string, imap: string, smtp: string) {
  await fs.mkdir(dir, { recursive: true, mode: 0o700 })
  await fs.writeFile(passFile(dir, id, 'imap'), imap, { mode: 0o600 })
  await fs.writeFile(passFile(dir, id, 'smtp'), smtp, { mode: 0o600 })
}

// ---- errors --------------------------------------------------------------------------

/** the useful line of an mbsync / msmtp failure, in words */
function explain(e: unknown, what: 'IMAP' | 'SMTP') {
  const text = (e instanceof ExecError ? e.stderr : (e as Error).message).trim()
  const lines = text.split('\n').map(l => l.trim()).filter(l => l && !/^(C: |S: |Channel |Opening|Connecting|Resolving|Logging in|Error: channel)/.test(l))
  const line = lines.find(l => /error|fail|refused|denied|invalid|cannot|could not|unable|timed out|NO |BAD /i.test(l)) ?? lines[0] ?? 'failed'
  if (/AUTHENTICATIONFAILED|authentication failed|Invalid credentials|Invalid login|LOGIN failed|535|EAUTH/i.test(text))
    return `${what}: the server refused the user name or password — many providers need an app password`
  if (/wrong version number|packet length too long|unexpected eof/i.test(text))
    return `${what}: the server does not speak TLS that way on this port — check the port and security setting`
  if (/certificate/i.test(line)) return `${what}: the server's certificate is not trusted — ${line.replace(/^.*?: /, '')}`
  if (/SSL|TLS/i.test(line)) return `${what}: TLS problem — ${line} (check the port and security setting)`
  if (/resolve|Name or service not known|not known|ENOTFOUND|EAI_AGAIN/i.test(text)) return `${what}: cannot find the server — ${line}`
  if (/refused|timed out|timeout|unreachable|ECONNREFUSED|ETIMEDOUT/i.test(text)) return `${what}: cannot connect — ${line}`
  return `${what}: ${line}`
}

// ---- testing and saving ----------------------------------------------------------------

function validate(a: AccountInput) {
  const bad = (s: unknown) => typeof s !== 'string' || !s.trim() || /[\n\r"'\\]/.test(s)
  if (!EMAIL_RE.test(a.email)) throw new BadRequest('that is not an email address')
  if (/[\n\r]/.test(a.name ?? '')) throw new BadRequest('bad name')
  for (const [what, s] of [['IMAP', a.imap], ['SMTP', a.smtp]] as const) {
    if (!s || bad(s.host) || /\s/.test(s.host)) throw new BadRequest(`${what}: server name missing or invalid`)
    if (!Number.isInteger(Number(s.port)) || Number(s.port) < 1 || Number(s.port) > 65535) throw new BadRequest(`${what}: bad port`)
    if (!['tls', 'starttls', 'none'].includes(s.security)) throw new BadRequest(`${what}: bad security`)
    if (bad(s.user)) throw new BadRequest(`${what}: user name missing or invalid`)
    s.port = Number(s.port)
    s.host = s.host.trim()
  }
  for (const p of [a.imapPassword, a.smtpPassword]) if (p && /[\n\r]/.test(p)) throw new BadRequest('passwords cannot contain line breaks')
}

const SENT_RE = /^(INBOX[./])?(Sent|Sent Items|Sent Messages|Sent Mail|Gesendet|Envoyés|Enviados|Verzonden)$/i

/**
 * Log in to IMAP with mbsync (listing the folders, to find the Sent folder) and to
 * SMTP, using a throwaway config so a mistake never touches the working one.
 */
async function test(a: ImapAccount, imapPassword: string, smtpPassword: string) {
  const dir = await fs.mkdtemp(path.join(tmpdir(), 'drewcmail-'))
  try {
    await writePasswords(dir, a.id, imapPassword, smtpPassword)
    await fs.mkdir(path.join(dir, 'mail', a.id), { recursive: true })   // mbsync opens the local side too
    await writeConfigs([a], dir, path.join(dir, 'mail'), dir)
    let folders: string[]
    try {
      const out = await exec(MBSYNC, ['-c', path.join(dir, 'mbsyncrc'), '--list', `${a.id}:*`], undefined, { timeout: TEST_TIMEOUT })
      folders = out.toString('utf8').split('\n').map(s => s.trim()).filter(Boolean)
    } catch (e) { throw new BadRequest(explain(e, 'IMAP')) }
    // msmtp cannot log in without sending; nodemailer's verify() connects and authenticates
    try {
      await nodemailer.createTransport({
        host: a.smtp.host, port: a.smtp.port,
        secure: a.smtp.security === 'tls', requireTLS: a.smtp.security === 'starttls', ignoreTLS: a.smtp.security === 'none',
        auth: { user: a.smtp.user, pass: smtpPassword },
        tls: a.ca ? { ca: await fs.readFile(a.ca) } : undefined,
        connectionTimeout: TEST_TIMEOUT, greetingTimeout: TEST_TIMEOUT,
      }).verify()
    } catch (e) { throw new BadRequest(explain(e, 'SMTP')) }
    return { folders, sent: folders.find(f => SENT_RE.test(f)) ?? 'Sent' }
  } finally {
    await fs.rm(dir, { recursive: true, force: true })
  }
}

/** add or change an account from the web app (never a Proton one: proton.ts owns those) */
export function save(input: AccountInput) {
  const { name, email, imap, smtp, id, imapPassword, smtpPassword } = input
  return saveAccount({ name, email, imap, smtp, id, imapPassword, smtpPassword })
}

/** add or change an account: test it, then save it and regenerate the configs */
export async function saveAccount(input: AccountInput & Pick<ImapAccount, 'proton' | 'ca'>) {
  validate(input)
  const all = await load()
  const old = input.id ? all.find(a => a.id === input.id) : undefined
  if (input.id && !old) throw new BadRequest('no such account')
  if (old?.proton && !input.proton) throw new BadRequest('this account belongs to Proton Mail Bridge — change it there')
  const id = old?.id ?? slug(input.email)
  if (!old && all.some(a => a.id === id)) throw new BadRequest(`${input.email} is already set up`)

  const imapPassword = input.imapPassword || (old ? await fs.readFile(passFile(PASS_DIR, id, 'imap'), 'utf8').catch(() => '') : '')
  const smtpPassword = input.smtpPassword || (old ? await fs.readFile(passFile(PASS_DIR, id, 'smtp'), 'utf8').catch(() => '') : '') || imapPassword
  if (!imapPassword) throw new BadRequest('enter the password')

  const account: ImapAccount = {
    id, name: (input.name ?? '').trim(), email: input.email.trim(),
    imap: { ...input.imap }, smtp: { ...input.smtp }, sentFolder: old?.sentFolder ?? 'Sent',
    ...(input.proton ? { proton: input.proton } : {}), ...(input.ca ? { ca: input.ca } : {}),
  }
  const { sent } = await test(account, imapPassword, smtpPassword)
  account.sentFolder = sent

  await writePasswords(PASS_DIR, id, imapPassword, smtpPassword)
  await store(old ? all.map(a => (a.id === id ? account : a)) : [...all, account])
  await notmuch.addIdentity(account.email, account.name)
  return account
}

/** stop syncing and sending as this account; its mail stays */
export async function remove(id: string, { proton = false } = {}) {
  const all = await load()
  const a = all.find(a => a.id === id)
  if (!a) throw new BadRequest('no such account')
  if (a.proton && !proton) throw new BadRequest('this account belongs to Proton Mail Bridge — remove it there')
  await store(all.filter(a => a.id !== id))
  for (const kind of ['imap', 'smtp'] as const) await fs.rm(passFile(PASS_DIR, id, kind), { force: true })
  status.delete(id)
}

// ---- sync and send -------------------------------------------------------------------

/** `skip`: accounts not to sync now, with the reason (Bridge not running) */
export async function syncAll(skip: (a: ImapAccount) => string | undefined = () => undefined) {
  const errors: string[] = []
  const all = await load()
  // regenerated every time, so the files always match accounts.json (and this version of the app)
  if (all.length) await writeConfigs(all, PASS_DIR, IMAP_DIR, CONFIG_DIR)
  for (const a of all) {
    const why = skip(a)
    if (why) { status.set(a.id, { syncing: false, ok: false, error: why, last: new Date().toISOString() }); continue }
    const s: Status = { ...(status.get(a.id) ?? {}), syncing: true }
    status.set(a.id, s)
    try {
      await fs.mkdir(path.join(IMAP_DIR, a.id), { recursive: true })
      await exec(MBSYNC, ['-c', MBSYNC_CONFIG, '--quiet', a.id], undefined, { timeout: SYNC_TIMEOUT })
      Object.assign(s, { ok: true, error: undefined })
    } catch (e) {
      Object.assign(s, { ok: false, error: explain(e, 'IMAP') })
      errors.push(`${a.email}: ${s.error}`)
    } finally {
      Object.assign(s, { syncing: false, last: new Date().toISOString() })
    }
  }
  if (errors.length) throw new Error(errors.join('\n'))
}

/**
 * send over SMTP; returns the Maildir folder (under /mail) for the Sent copy, which
 * mbsync uploads — or null when the server files it itself (Proton does)
 */
export async function send(a: ImapAccount, from: string, to: string[], raw: Buffer) {
  try {
    await exec(MSMTP, ['-C', MSMTP_CONFIG, '-a', a.id, '-f', from, '--', ...to], raw, { timeout: 2 * 60_000 })
  } catch (e) { throw new BadRequest(explain(e, 'SMTP')) }
  return a.proton ? null : path.posix.join('imap', a.id, a.sentFolder)
}

const TRASH = ['Trash', 'Deleted Items', 'Deleted Messages', 'Deleted', 'Bin']
const SPAM = ['Junk', 'Spam', 'Junk E-mail', 'Junk Email', 'Bulk Mail']
const DRAFTS = ['Drafts', 'Draft']

/**
 * How fresh mail (tag:new) from IMAP is tagged by the folder it is in: only INBOX is
 * the inbox; Sent/Trash/Spam folders become sent/deleted/spam. Read state comes from
 * the IMAP flags (maildir.synchronize_flags), not from here.
 */
export async function newMailRules(): Promise<{ query: string; add: string[]; remove: string[] }[]> {
  const folders = (a: ImapAccount, names: string[]) =>
    names.flatMap(n => [n, `INBOX/${n}`, `INBOX.${n}`]).map(n => `folder:"imap/${a.id}/${n}"`).join(' or ')
  return (await load()).flatMap(a => [
    { query: `folder:"imap/${a.id}/INBOX"`, add: ['inbox'], remove: [] },
    { query: `folder:"imap/${a.id}/${a.sentFolder}" or ${folders(a, ['Sent'])}`, add: ['sent'], remove: ['unread'] },
    { query: folders(a, TRASH), add: ['deleted'], remove: [] },
    { query: folders(a, SPAM), add: ['spam'], remove: [] },
    { query: folders(a, DRAFTS), add: ['draft'], remove: [] },
  ])
}

// ---- finding the servers -------------------------------------------------------------

type Found = { imap?: Omit<Server, 'user'> & { user?: string }; smtp?: Omit<Server, 'user'> & { user?: string } }
export type Discovery = { source: string; provider?: string; imap: Server; smtp: Server; hint?: string; gmail?: boolean; proton?: boolean }

const SOCKET: Record<string, Security> = { SSL: 'tls', STARTTLS: 'starttls', plain: 'none' }

/** the first IMAP and SMTP server of a Thunderbird autoconfig document */
function parseAutoconfig(xml: string, email: string): Found & { provider?: string } {
  const [local, domain] = email.split('@')
  const fill = (s = '') => s.replace(/%EMAILADDRESS%/g, email).replace(/%EMAILLOCALPART%/g, local).replace(/%EMAILDOMAIN%/g, domain)
  const tag = (block: string, name: string) => block.match(new RegExp(`<${name}>\\s*([^<]*?)\\s*</${name}>`))?.[1]
  const server = (re: RegExp) => {
    const block = xml.match(re)?.[1]
    if (!block) return undefined
    const host = tag(block, 'hostname'), port = Number(tag(block, 'port'))
    if (!host || !port) return undefined
    return { host: fill(host), port, security: SOCKET[tag(block, 'socketType') ?? ''] ?? (port === 993 || port === 465 ? 'tls' : 'starttls'), user: fill(tag(block, 'username')) || undefined }
  }
  return {
    provider: tag(xml, 'displayName'),
    imap: server(/<incomingServer type="imap">([\s\S]*?)<\/incomingServer>/),
    smtp: server(/<outgoingServer type="smtp">([\s\S]*?)<\/outgoingServer>/),
  }
}

async function fetchText(url: string) {
  try {
    const res = await fetch(url, { signal: AbortSignal.timeout(5000), redirect: 'follow' })
    return res.ok ? await res.text() : null
  } catch { return null }
}

const HINTS: [RegExp, string][] = [
  [/(^|\.)(icloud|me|mac)\.com$/, 'iCloud needs an app-specific password: appleid.apple.com → Sign-In and Security → App-Specific Passwords.'],
  [/(^|\.)(yahoo|ymail|rocketmail)\.|(^|\.)aol\.com$/, 'Yahoo/AOL need an app password: Account security → Generate app password.'],
  [/(^|\.)(fastmail|messagingengine)\.com$/, 'Fastmail needs an app password: Settings → Privacy & Security → App passwords.'],
  [/(^|\.)(outlook|hotmail|live|msn)\.com$|office365\.com$/, 'Microsoft has turned off passwords for IMAP on Outlook.com and most Microsoft 365 accounts; this will likely be refused.'],
  [/(^|\.)zoho\./, 'With two-factor sign-in on, Zoho needs an app-specific password.'],
  [/(^|\.)gmx\./, 'GMX: turn on "POP3/IMAP access" in the web settings first.'],
]

/** find the IMAP and SMTP servers for an address, as Thunderbird does */
export async function discover(email: string): Promise<Discovery> {
  email = email.trim()
  if (!EMAIL_RE.test(email)) throw new BadRequest('that is not an email address')
  const domain = email.split('@')[1].toLowerCase()
  const q = encodeURIComponent(email)
  let mxHost = ''
  const mxDomain = async () => {
    const mx = await resolveMx(domain).catch(() => [])
    mxHost = mx.sort((a, b) => a.priority - b.priority)[0]?.exchange?.toLowerCase() ?? ''
    return mxHost.split('.').slice(-2).join('.')
  }
  const gmail = (host: string) => /(^|\.)(gmail|googlemail)\.com$|(^|\.)google\.com$/.test(host)

  let found: ReturnType<typeof parseAutoconfig> = {}
  let source = ''
  const sources: [string, () => Promise<string | null>][] = [
    ['the provider', () => fetchText(`https://autoconfig.${domain}/mail/config-v1.1.xml?emailaddress=${q}`)],
    ['the provider', () => fetchText(`https://${domain}/.well-known/autoconfig/mail/config-v1.1.xml?emailaddress=${q}`)],
    ["Thunderbird's database", () => fetchText(`https://autoconfig.thunderbird.net/v1.1/${domain}`)],
    ["Thunderbird's database (via MX)", async () => { const d = await mxDomain(); return d && d !== domain ? fetchText(`https://autoconfig.thunderbird.net/v1.1/${d}`) : null }],
  ]
  for (const [name, get] of sources) {
    const xml = await get()
    if (!xml) continue
    const f = parseAutoconfig(xml, email)
    if (f.imap && f.smtp) { found = f; source = name; break }
  }
  if (!mxHost) await mxDomain()
  if (!found.imap || !found.smtp) {
    found = { imap: { host: `imap.${domain}`, port: 993, security: 'tls' }, smtp: { host: `smtp.${domain}`, port: 465, security: 'tls' } }
    source = 'a guess'
  }
  const isGmail = gmail(domain) || gmail(mxHost) || gmail(found.imap!.host)
  // Proton has no IMAP of its own: it goes through Proton Mail Bridge
  const isProton = /(^|\.)(proton\.me|protonmail\.com|protonmail\.ch|pm\.me)$/.test(domain) || /(^|\.)protonmail\.ch$/.test(mxHost)
  return {
    source,
    provider: found.provider,
    imap: { ...found.imap!, user: found.imap!.user ?? email },
    smtp: { ...found.smtp!, user: found.smtp!.user ?? email },
    hint: HINTS.find(([re]) => re.test(domain) || re.test(found.imap!.host))?.[1],
    gmail: isGmail || undefined,
    proton: isProton || undefined,
  }
}
